# Turns the Blockbench renders into the demo's images and writes demos/pc-unwrap/lib/art.luau: the
# projection (render pixels of a point in centimetres, measured from the calibration markers) and,
# for every image, where its top-left corner sits in render pixels and how many render pixels one
# image pixel covers. The demo places all layers and its live meshes with these numbers.
#
# Usage: python art/pc-unwrap/postprocess.py RENDERS GAME
#   RENDERS holds <name>_lit.png renders (see README.md) and calib.png; GAME is demos/pc-unwrap.
import glob, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pngtools import read_png, write_png, remove_shadow, alpha_bbox, crop, scale_down  # noqa: E402
import scene  # noqa: E402

# Image scale per layer (the PC is seen close up, the box from further away).
SCALE = {"pc": 0.75}
DEFAULT_SCALE = 0.5


def solve(a, b):
    """Gaussian elimination for a small dense system."""
    n = len(b)
    m = [row[:] + [b[i]] for i, row in enumerate(a)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        m[c], m[p] = m[p], m[c]
        for r in range(n):
            if r != c:
                f = m[r][c] / m[c][c]
                for k in range(c, n + 1):
                    m[r][k] -= f * m[c][k]
    return [m[i][n] / m[i][i] for i in range(n)]


def calibrate(path):
    """Fits screen = origin + x ex + y ey + z ez to the marker centroids (least squares)."""
    w, h, px = read_png(path)
    clusters = []
    for y in range(h):
        for x in range(w):
            i = (y * w + x) * 4
            if px[i + 3] < 128:
                continue
            for c in clusters:
                if abs(c[0] / c[2] - x) < 30 and abs(c[1] / c[2] - y) < 30:
                    c[0] += x + 0.5
                    c[1] += y + 0.5
                    c[2] += 1
                    for k in range(3):
                        c[3 + k] += px[i + k]
                    break
            else:
                clusters.append([x + 0.5, y + 0.5, 1, px[i], px[i + 1], px[i + 2]])
    assert len(clusters) == len(scene.MARKERS), "found %d markers" % len(clusters)
    pts = []
    for c in clusters:
        rgb = [c[3 + k] / c[2] for k in range(3)]
        lo, hi = min(rgb), max(rgb)
        norm = [(v - lo) / (hi - lo + 1e-6) * 255 for v in rgb]
        if hi - lo < 30:
            norm = [255, 255, 255]  # the white marker (lit, it stays grey)
        best = min(range(len(scene.MARKERS)), key=lambda k: sum((norm[j] - scene.MARKERS[k][1][j]) ** 2 for j in range(3)))
        pts.append((scene.MARKERS[best][0], (c[0] / c[2], c[1] / c[2])))
    assert len({p[0] for p in pts}) == len(pts), "markers matched twice"
    fit = []
    for axis in range(2):
        ata = [[0.0] * 4 for _ in range(4)]
        atb = [0.0] * 4
        for (x, y, z), s in pts:
            row = [1.0, x, y, z]
            for i in range(4):
                atb[i] += row[i] * s[axis]
                for j in range(4):
                    ata[i][j] += row[i] * row[j]
        fit.append(solve(ata, atb))
    err = max(abs(fit[a][0] + fit[a][1] * x + fit[a][2] * y + fit[a][3] * z - s[a]) for (x, y, z), s in pts for a in range(2))
    print("calibration: max error %.2f px" % err)
    return fit


def main():
    renders, game = sys.argv[1], sys.argv[2]
    fit = calibrate(os.path.join(renders, "calib.png"))
    entries = []
    for path in sorted(glob.glob(os.path.join(renders, "*_lit.png"))):
        name = os.path.basename(path)[:-len("_lit.png")]
        w, h, px = read_png(path)
        px = remove_shadow(w, h, px)
        box = alpha_bbox(w, h, px)
        box = (max(0, box[0] - 2), max(0, box[1] - 2), min(w, box[2] + 2), min(h, box[3] + 2))
        cw, ch, cp = crop(w, h, px, box)
        f = SCALE.get(name, DEFAULT_SCALE)
        cw, ch, cp = scale_down(cw, ch, cp, f)
        out = os.path.join(game, "images", "pc", name + ".png")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        write_png(out, cw, ch, cp)
        entries.append((name, box[0], box[1], 1 / f))
        print("wrote", out, cw, ch)
    lines = [
        "-- Generated by art/pc-unwrap/postprocess.py from the Blockbench renders; do not edit.",
        "-- Render pixels of a point (x, y, z) in centimetres are origin + x * ex + y * ey + z * ez",
        "-- (the case: x -23..23 front to back, y 0..49 up, z -11.5..11.5 from the glass side).",
        "-- Each image's top-left corner sits at (x, y) render pixels; one image pixel covers `scale`.",
        "return {",
        "    origin = { %.3f, %.3f }," % (fit[0][0], fit[1][0]),
        "    ex = { %.4f, %.4f }," % (fit[0][1], fit[1][1]),
        "    ey = { %.4f, %.4f }," % (fit[0][2], fit[1][2]),
        "    ez = { %.4f, %.4f }," % (fit[0][3], fit[1][3]),
        "    images = {",
    ]
    for name, x, y, s in entries:
        lines.append('        %s = { path = "images/pc/%s.png", x = %d, y = %d, scale = %g },' % (name, name, x, y, s))
    lines += ["    },", "}", ""]
    open(os.path.join(game, "lib", "art.luau"), "w", newline="\n").write("\n".join(lines))
    print("wrote", os.path.join(game, "lib", "art.luau"))


if __name__ == "__main__":
    main()
